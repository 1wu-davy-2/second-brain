async function request(path, init) {
  const response = await fetch(`${base}${path}`, {
    ...init,
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
      ...(init?.headers ?? {}),
    },
  });
  const text = await response.text();
  if (!response.ok) throw new Error(`${response.status} ${text.slice(0, 200)}`);
  return text ? JSON.parse(text) : null;
}

const created = [];
let skipped = 0;

for (const note of notes) {
  // 幂等：同名笔记已存在就跳过，重复执行不会产生副本
  const found = await request(`/api/v1/notes?q=${encodeURIComponent(note.title)}&limit=20`);
  if (found.notes.some((item) => item.title === note.title)) {
    skipped += 1;
    console.log(`= 跳过（已存在）${note.title}`);
    continue;
  }

  const result = await request("/api/v1/notes", {
    method: "POST",
    body: JSON.stringify(note),
  });
  created.push({ id: result.note.id, title: result.note.title });
  console.log(`+ ${result.note.title}`);
}

// 第二遍回写：让先创建时找不到目标的 [[链接]] 重新解析，回链才会出现
for (const note of created) {
  const source = notes.find((item) => item.title === note.title);
  await request(`/api/v1/notes/${note.id}`, {
    method: "PATCH",
    body: JSON.stringify({ content: source.content, tags: source.tags }),
  });
}
console.log(`\n✓ 新建 ${created.length} 篇，跳过 ${skipped} 篇，已重建链接`);
